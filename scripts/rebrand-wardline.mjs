const BINARY_EXT = /\.(woff2?|ttf|otf|png|jpe?g|gif|webp|ico|wasm|pdf|zip|gz|lock\.bin)$/i;

export function repoRoot() {
  return execFileSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8" }).trim();
}

/** Tracked files plus untracked files that are not ignored. Sorted, so runs are reproducible. */
export function listFiles(root = repoRoot()) {
  const out = execFileSync("git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard"], { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  return [...new Set(out.split("\0").filter(Boolean))].filter((f) => existsSync(join(root, f))).sort();
}

export const skipEntry = (file) => SKIP_PATHS.find((s) => (s.prefix || s.path.endsWith("/") ? file.startsWith(s.path) : file === s.path));

export function isBinary(file, buf) {
  if (BINARY_EXT.test(file)) return true;
  return buf.subarray(0, 8000).includes(0);
}

/** Replaces legacy spans with placeholders. Returns the masked text and a restore function. */
export function protect(text) {
  const kept = [];
  let masked = text;
  for (const { pattern } of LEGACY_SPANS) {
    masked = masked.replace(pattern, (m) => {
      kept.push(m);
      return `\u0000${kept.length - 1}\u0000`;
    });
  }
  return { masked, kept, restore: (s) => s.replace(/\u0000(\d+)\u0000/g, (_, i) => kept[Number(i)]) };
}

/** Rewrites one text. Counts go into `counts` by rule name. */
export function rewrite(text, counts = {}, { prose = true } = {}) {
  const { masked, kept, restore } = protect(text);
  let out = masked;
  for (const rule of RULES) {
    if (rule.prose && !prose) continue;
    out = out.replace(rule.pattern, (m) => {
      counts[rule.name] = (counts[rule.name] ?? 0) + 1;
      return rule.to(m);
    });
  }
  if (kept.length) counts["legacy spans kept"] = (counts["legacy spans kept"] ?? 0) + kept.length;
  return restore(out);
}

/** New path for a file, segment by segment. */
export function renamePath(file) {
  return file
    .split("/")
    .map((seg) => rewrite(seg, {}, { prose: false }))
    .join("/");
}

/** Renames old env var names in a local .env. Values are never printed or logged. */
function migrateDotEnv(root, dry) {
  const file = join(root, ".env");
  if (!existsSync(file)) return { exists: false, renamed: [], commented: [] };
  const text = readFileSync(file, "utf8");
  const lines = text.split(/(\r?\n)/);
  const keyOf = (line) => /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/.exec(line)?.[1];
  const present = new Set(lines.map(keyOf).filter(Boolean));
  const renamed = [];
  const commented = [];
  const out = lines.map((line) => {
    const key = keyOf(line);
    if (!key || !/^(?:VITE_)?(?:REDLINE|SPEND_?GYM)_/i.test(key)) return line;
    const next = rewrite(key, {}, { prose: false });
    if (present.has(next)) {
      // The new name is already set. Keep the old line, commented, rather than lose a value.
      commented.push(key);
      return `# ${line}`;
    }
    renamed.push(`${key} -> ${next}`);
    return line.replace(key, next);
  });
  if (!dry && (renamed.length || commented.length)) writeFileSync(file, out.join(""));
  return { exists: true, renamed, commented };
}

function removeEmptyDirs(root, dirs) {
  for (const dir of [...dirs].sort((a, b) => b.length - a.length)) {
    let d = dir;
    while (d && d !== ".") {
      const abs = join(root, d);
      if (!existsSync(abs) || readdirSync(abs).length) break;
      rmdirSync(abs);
      d = dirname(d);
    }
  }
}

export function run({ dry = false, list = false, root = repoRoot(), log = console.log } = {}) {
  const files = listFiles(root);
  const counts = {};
  const changed = [];
  const renames = [];
  const skipped = {};
  let scanned = 0;
  let binary = 0;

  for (const file of files) {
    const skip = skipEntry(file);
    if (skip) {
      skipped[skip.path] = (skipped[skip.path] ?? 0) + 1;
      continue;
    }
    const abs = join(root, file);
    const buf = readFileSync(abs);
    const next = renamePath(file);
    if (next !== file) renames.push([file, next]);
    if (isBinary(file, buf)) {
      binary++;
      continue;
    }
    scanned++;
    const text = buf.toString("utf8");
    const out = rewrite(text, counts);
    if (out !== text) {
      changed.push(file);
      if (!dry) writeFileSync(abs, out);
    }
  }

  const collisions = renames.filter(([, to]) => existsSync(join(root, to)));
  if (collisions.length) throw new Error(`Rename targets already exist: ${collisions.map(([f, t]) => `${f} -> ${t}`).join(", ")}`);
  if (!dry) {
    const oldDirs = new Set();
    for (const [from, to] of renames) {
      mkdirSync(dirname(join(root, to)), { recursive: true });
      renameSync(join(root, from), join(root, to));
      oldDirs.add(dirname(from));
    }
    removeEmptyDirs(root, oldDirs);
  }

  const env = migrateDotEnv(root, dry);
  const verb = dry ? "would change" : "changed";
  log(`Wardline rebrand${dry ? " (dry run, nothing written)" : ""}`);
  log(`  files listed:      ${files.length}`);
  log(`  text files read:   ${scanned}  (binary skipped: ${binary})`);
  log(`  files ${verb}: ${changed.length}`);
  log(`  files to rename:   ${renames.length}`);
  log("  replacements:");
  const names = Object.keys(counts).sort();
  if (!names.length) log("    none");
  for (const name of names) log(`    ${String(counts[name]).padStart(6)}  ${name}`);
  log("  skipped paths:");
  for (const s of SKIP_PATHS) if (skipped[s.path]) log(`    ${String(skipped[s.path]).padStart(6)}  ${s.path}  (${s.why})`);
  log(`  .env: ${!env.exists ? "none" : `${env.renamed.length} key(s) renamed, ${env.commented.length} old duplicate(s) commented out`}`);
  for (const r of env.renamed) log(`    ${r}`);
  for (const c of env.commented) log(`    ${c} (new name already set)`);
  if (renames.length) {
    log("  renames:");
    for (const [from, to] of renames) log(`    ${from} -> ${to}`);
  }
  if (list && changed.length) {
    log("  changed files:");
    for (const f of changed) log(`    ${f}`);
  }
  if (!dry && (changed.length || renames.length)) {
    log("Next: pnpm install (regenerates pnpm-lock.yaml), then pnpm test.");
    log("If evidence/example-run changed on this branch, regenerate it:");
    log("  pnpm --filter @wardline/evaluator exec tsx src/cli.ts run --split dev --agents rules-stub,always-review,credulous-stub --out evidence/example-run --publish-salt");
  }
  return { files: files.length, scanned, changed, renames, counts, env };
}

const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invokedDirectly) {
  const args = new Set(process.argv.slice(2));
  const unknown = [...args].filter((a) => !["--dry-run", "--list", "--help"].includes(a));
  if (args.has("--help") || unknown.length) {
    console.log("Usage: node scripts/rebrand-wardline.mjs [--dry-run] [--list]");
    process.exit(unknown.length ? 1 : 0);
  }
  run({ dry: args.has("--dry-run"), list: args.has("--list") });
}

