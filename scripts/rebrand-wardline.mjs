#!/usr/bin/env node
/**
 * Renames the product to Wardline in file contents and file names. Also clears the older
 * "Spend Gym" name and its sgUSD token.
 *
 *   node scripts/rebrand-wardline.mjs --dry-run   # report only
 *   node scripts/rebrand-wardline.mjs             # rewrite and rename
 *   node scripts/rebrand-wardline.mjs --list      # also print every file it changes
 *
 * Deterministic: it reads the files git knows about (tracked, plus untracked files that are not
 * ignored), applies fixed rules in a fixed order and depends on nothing else. Idempotent: a second
 * run changes nothing. No dependencies beyond Node.
 *
 * After it runs: pnpm install (regenerates pnpm-lock.yaml), pnpm test. The summary prints the rest.
 *
 * The guard test (tests/brand.test.mjs) imports the allowlists below, so they live in one place.
 */

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const TOKEN_SYMBOL = "WUSD";
export const TOKEN_NAME = "Wardline Test Dollar";

/**
 * Old-name spans that must stay byte-for-byte, because they name something that already exists
 * and cannot be renamed. The rewrite never touches them and the guard test allows them.
 */
export const LEGACY_SPANS = [
  // Live testnet root account of the current deployment, and every account under it.
  { pattern: /(?:[a-z0-9_-]+\.)*redline-labs(?:\.testnet)?/g, why: "live testnet accounts under redline-labs.testnet" },
  // Earlier testnet root. Contracts still exist on chain.
  { pattern: /(?:[a-z0-9_-]+\.)*redlinehq(?:\.testnet)?/g, why: "earlier testnet accounts under redlinehq.testnet" },
  // Seed of the committed red-team cases. The recorded model outputs are keyed to cases built from it.
  { pattern: /redline-redteam-v1/g, why: "seed of the recorded red-team fixtures" },
];

/**
 * Paths the rewrite never touches. `legacy: true` means old names may stay there for good and the
 * guard test allows them. The others are regenerated instead of rewritten, and must end up clean.
 */
export const SKIP_PATHS = [
  { path: "scripts/rebrand-wardline.mjs", legacy: true, why: "this codemod" },
  { path: "packages/schemas/src/legacy-env.ts", legacy: true, why: "reads the old env var names as a fallback" },
  { path: "packages/schemas/test/legacy-env.test.ts", legacy: true, why: "tests that fallback" },
  { path: "docs/status/", legacy: true, why: "status history is left as written; titles and current state are edited by hand" },
  { path: "fixtures/redteam/", legacy: true, why: "recorded red-team fixtures and model outputs, keyed by content hash" },
  { path: "scripts/contracts/deployments/testnet", prefix: true, legacy: true, why: "records of live testnet deployments, including on-chain token metadata" },
  { path: "fixtures/private/", legacy: true, why: "hidden assessment suite, never touched" },
  { path: "pnpm-lock.yaml", legacy: false, why: "regenerated by pnpm install" },
  { path: "evidence/example-run/", legacy: false, why: "digests would break; regenerated by the evaluator" },
  { path: ".env", legacy: false, why: "handled by the .env step, values never read out" },
];

/** Every old name the guard looks for. */
export const OLD_NAMES = /redline|\bredl\b|spend[ _-]?gym|\bsg-?usd\b/gi;

const isUpper = (s) => s === s.toUpperCase() && s !== s.toLowerCase();
const isLower = (s) => s === s.toLowerCase();
/** WARDLINE for REDLINE, wardline for redline, Wardline for Redline and any other mix. */
const cased = (match, lower) => (isUpper(match) ? lower.toUpperCase() : isLower(match) ? lower : lower[0].toUpperCase() + lower.slice(1));

/** Applied in order. Prose fixes first, so a pun on the English word never becomes the product name. */
export const RULES = [
  { name: "prose: 'has a redline' (a limit, not the product)", pattern: /\bhas a redline\b/g, to: () => "has a limit", prose: true },
  { name: "token name", pattern: /\b(?:Redline|Spend Gym) Test Dollar\b/g, to: () => TOKEN_NAME, prose: true },
  { name: "Spend Gym -> Wardline", pattern: /spend[ _-]?gym/gi, to: (m) => cased(m.replace(/[ _-]/g, ""), "wardline") },
  { name: "sgUSD -> " + TOKEN_SYMBOL, pattern: /\bsg-?usd\b/gi, to: (m) => (isLower(m) ? TOKEN_SYMBOL.toLowerCase() : TOKEN_SYMBOL) },
  { name: "Redline -> Wardline", pattern: /redline/gi, to: (m) => cased(m, "wardline") },
  { name: "REDL -> " + TOKEN_SYMBOL, pattern: /\bredl\b/gi, to: (m) => cased(m, TOKEN_SYMBOL.toLowerCase()) },
];

